package com.j21.telecom.dto;

import java.math.BigDecimal;
import java.time.LocalDateTime;

public class ServicePlanResponseDTO {

    private Long planId;
    private String planName;
    private String planType;
    private String description;
    private BigDecimal monthlyPrice;
    private BigDecimal dataLimitGb;
    private Integer validityDays;
    private Boolean isAvailable;
    private LocalDateTime createdAt;

    public Long getPlanId() {
        return planId;
    }

    public void setPlanId(Long planId) {
        this.planId = planId;
    }

    public String getPlanName() {
        return planName;
    }

    public void setPlanName(String planName) {
        this.planName = planName;
    }

    public String getPlanType() {
        return planType;
    }

    public void setPlanType(String planType) {
        this.planType = planType;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public BigDecimal getMonthlyPrice() {
        return monthlyPrice;
    }

    public void setMonthlyPrice(BigDecimal monthlyPrice) {
        this.monthlyPrice = monthlyPrice;
    }

    public BigDecimal getDataLimitGb() {
        return dataLimitGb;
    }

    public void setDataLimitGb(BigDecimal dataLimitGb) {
        this.dataLimitGb = dataLimitGb;
    }

    public Integer getValidityDays() {
        return validityDays;
    }

    public void setValidityDays(Integer validityDays) {
        this.validityDays = validityDays;
    }

    public Boolean getIsAvailable() {
        return isAvailable;
    }

    public void setIsAvailable(Boolean isAvailable) {
        this.isAvailable = isAvailable;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
}